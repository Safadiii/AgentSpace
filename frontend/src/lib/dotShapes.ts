function hermes(c: Ctx, w: number, h: number) {
  const frame = hermesFrame(w, h)
  const ivory = c.createLinearGradient(0, frame.y, 0, frame.y + frame.h)
  ivory.addColorStop(0, g(.99))
  ivory.addColorStop(.6, g(.91))
  ivory.addColorStop(1, g(.79))
  c.fillStyle = ivory
  c.beginPath()
  // Even-odd makes openings such as the brow and brooch transparent.
  for (const id of Object.keys(HERMES_MARK_REGIONS)) {
    hermesContour(c, frame, Number(id))
  }
  c.fill('evenodd')
}


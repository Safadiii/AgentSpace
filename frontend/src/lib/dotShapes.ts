function athenaFrame(w: number, h: number) {
  const maxW = w * .72
  const boxH = Math.min(h * .92, maxW / ATHENA_MARK_RATIO)
  const boxW = boxH * ATHENA_MARK_RATIO
  return { x: (w - boxW) / 2, y: (h - boxH) / 2, w: boxW, h: boxH }
}

function tracePoly(c: Ctx, points: [number, number][], px: (x: number) => number, py: (y: number) => number) {
  points.forEach(([x, y], i) => i ? c.lineTo(px(x), py(y)) : c.moveTo(px(x), py(y)))
  c.closePath()
}

function fillAthenaMark(c: Ctx, w: number, h: number, fillStyle: string | CanvasGradient) {
  const frame = athenaFrame(w, h)
  const px = (x: number) => frame.x + frame.w * x
  const py = (y: number) => frame.y + frame.h * y
  c.fillStyle = fillStyle
  c.beginPath()
  ATHENA_MARK_POLYS.forEach(poly => tracePoly(c, poly, px, py))
  ATHENA_MARK_HOLES.forEach(hole => tracePoly(c, hole, px, py))
  c.fill('evenodd')
}




from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import SystemMessage, HumanMessage


class NVIDIATopicExplorer:

    ANGLE_INSTRUCTIONS = {
        "applications": (
            "Find a specific real-world application or use case "
            "of the main research topic."
        ),
        "methodological approaches": (
            "Find a related algorithm, technique, or methodology "
            "that could expand research into this topic."
        ),
        "adjacent research fields": (
            "Find a neighboring research field with a meaningful "
            "connection to the main topic."
        ),
    }

    def __init__(self, llm: BaseChatModel):
        self.llm = llm

    async def suggest_topic(
        self,
        base_topic: str,
        angle: str
    ) -> str:

        base_topic = " ".join(base_topic.split())

        if not base_topic:
            raise ValueError("Main research topic cannot be empty")

        if angle not in self.ANGLE_INSTRUCTIONS:
            raise ValueError(
                f"Unsupported exploration angle: {angle}"
            )

        instruction = self.ANGLE_INSTRUCTIONS[angle]

        messages = [
            SystemMessage(
                content=(
                    "You are an academic research topic discovery agent. "
                    "Your job is to propose a related topic suitable "
                    "for searching academic papers on OpenAlex. "

                    "Return exactly ONE specific research topic. "
                    "Keep it between 3 and 12 words. "
                    "Do not include explanations, lists, quotes, "
                    "markdown, or introductory phrases. "
                    "Do not repeat the original topic unchanged."
                )
            ),

            HumanMessage(
                content=(
                    f"Main research topic: {base_topic}\n"
                    f"Exploration angle: {angle}\n"
                    f"Objective: {instruction}"
                )
            ),
        ]

        response = await self.llm.ainvoke(messages)

        if not isinstance(response.content, str):
            raise ValueError("Unexpected LLM response format")

        topic = response.content.strip()

        topic = topic.strip("\"'`")

        if "\n" in topic:
            topic = topic.splitlines()[0].strip()

        topic = " ".join(topic.split())

        if not topic or len(topic) > 150:
            raise ValueError("Invalid topic generated by LLM")

        if topic.casefold() == base_topic.casefold():
            raise ValueError("LLM repeated the original topic")

        return topic
